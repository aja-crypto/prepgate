export function getDailyQuestion() {
  const today = new Date().toISOString().slice(0, 10);
  const dayNum = today.split('-').reduce((acc, s) => acc + parseInt(s), 0);
  return GATE_FAQ[dayNum % GATE_FAQ.length];
}
